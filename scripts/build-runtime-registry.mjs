import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const rulesPath = path.join(root, "research", "rules_registry.json");
const sourcesPath = path.join(root, "research", "sources_registry.json");

const rulesDocument = JSON.parse(await readFile(rulesPath, "utf8"));
const sourcesDocument = JSON.parse(await readFile(sourcesPath, "utf8"));
const { countries, rules } = rulesDocument;
const { sources } = sourcesDocument;

function fail(message) {
  throw new Error(`Registry validation failed: ${message}`);
}

if (!Array.isArray(countries) || countries.length !== 42) fail(`expected 42 countries, received ${countries?.length ?? "none"}`);
if (!Array.isArray(rules) || rules.length !== 694) fail(`expected 694 rules, received ${rules?.length ?? "none"}`);
if (!Array.isArray(sources) || sources.length !== 426) fail(`expected 426 sources, received ${sources?.length ?? "none"}`);

const unique = (records, key, label) => {
  const values = records.map((record) => record[key]);
  if (values.some((value) => !value)) fail(`${label} contains a missing ${key}`);
  if (new Set(values).size !== values.length) fail(`${label} contains duplicate ${key} values`);
};

unique(countries, "code", "countries");
unique(rules, "rule_id", "rules");
unique(sources, "source_id", "sources");

const countryCodes = new Set(countries.map((country) => country.code));
const sourceIds = new Set(sources.map((source) => source.source_id));
const allowedStatuses = new Set(["verified", "mapped", "partial", "publishable", "retired"]);
const allowedSpecificities = new Set(["exact_national_rule", "route_mapping", "research_prompt"]);

for (const rule of rules) {
  if (!countryCodes.has(rule.destination_country)) fail(`${rule.rule_id} references unknown country ${rule.destination_country}`);
  if (!allowedStatuses.has(rule.review_status)) fail(`${rule.rule_id} has unknown review status ${rule.review_status}`);
  if (!allowedSpecificities.has(rule.rule_specificity)) fail(`${rule.rule_id} has unknown specificity ${rule.rule_specificity}`);
  for (const sourceId of rule.source_ids || []) {
    if (!sourceIds.has(sourceId)) fail(`${rule.rule_id} references missing source ${sourceId}`);
  }
}

const sharedJurisdictions = new Set(["MULTI", "EU", "EAEU"]);
for (const source of sources) {
  if (!sharedJurisdictions.has(source.jurisdiction) && !countryCodes.has(source.jurisdiction)) {
    fail(`${source.source_id} references unknown jurisdiction ${source.jurisdiction}`);
  }
}

function tierForRule(rule) {
  if (rule.rule_specificity === "exact_national_rule" && ["verified", "publishable"].includes(rule.review_status)) return "ready";
  if (rule.rule_specificity === "research_prompt") return "research";
  return "confirm";
}

const counts = {
  countries: countries.length,
  rules: rules.length,
  sources: sources.length,
  ready: rules.filter((rule) => tierForRule(rule) === "ready").length,
  confirm: rules.filter((rule) => tierForRule(rule) === "confirm").length,
  research: rules.filter((rule) => tierForRule(rule) === "research").length,
};

const runtimeDocument = {
  schema_version: rulesDocument.schema_version,
  catalog_version: rulesDocument.catalog_version,
  generated_at: rulesDocument.generated_at,
  legal_notice: rulesDocument.legal_notice,
  counts,
  countries,
  rules: rules.map((rule) => ({ ...rule, runtime_tier: tierForRule(rule) })),
  sources,
};

const moduleText = `// Generated by scripts/build-runtime-registry.mjs. Do not edit by hand.\n`
  + `export const REGISTRY = ${JSON.stringify(runtimeDocument)};\n`
  + `export const REGISTRY_COUNTRIES = REGISTRY.countries;\n`
  + `export const REGISTRY_RULES = REGISTRY.rules;\n`
  + `export const REGISTRY_SOURCES = REGISTRY.sources;\n`
  + `export const REGISTRY_COUNTS = REGISTRY.counts;\n`;

await mkdir(path.join(root, "dist"), { recursive: true });
await mkdir(path.join(root, "external-saas", "catalog"), { recursive: true });
await writeFile(path.join(root, "dist", "registry.mjs"), moduleText);
await writeFile(path.join(root, "external-saas", "catalog", "registry.json"), `${JSON.stringify(runtimeDocument, null, 2)}\n`);

console.log(`Registry built: ${counts.countries} countries, ${counts.rules} rules, ${counts.sources} sources (${counts.ready} ready / ${counts.confirm} confirm / ${counts.research} research)`);
